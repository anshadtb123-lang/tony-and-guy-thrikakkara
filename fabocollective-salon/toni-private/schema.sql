CREATE TABLE IF NOT EXISTS site (
 id TINYINT PRIMARY KEY, headline VARCHAR(160) NOT NULL, intro VARCHAR(400) NOT NULL, story TEXT NOT NULL,
 book_label VARCHAR(48) NOT NULL, book_target VARCHAR(500) NOT NULL, explore_label VARCHAR(48) NOT NULL, explore_target VARCHAR(500) NOT NULL,
 logo VARCHAR(100) NOT NULL, hero VARCHAR(100) NOT NULL, hero_alt VARCHAR(240) NOT NULL,
 phone VARCHAR(32) NOT NULL, email VARCHAR(254) NOT NULL, address VARCHAR(350) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS services (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, description VARCHAR(400) NOT NULL, image VARCHAR(100) NOT NULL DEFAULT '', position INT NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS gallery (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, alt VARCHAR(240) NOT NULL, caption VARCHAR(240) NOT NULL DEFAULT '', image VARCHAR(100) NOT NULL, position INT NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS owners (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) UNIQUE NOT NULL, hash VARCHAR(255) NOT NULL, version INT NOT NULL DEFAULT 1, initial_password BOOLEAN NOT NULL DEFAULT 1) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS attempts (ip CHAR(64) PRIMARY KEY, since DATETIME NOT NULL, hits INT UNSIGNED NOT NULL) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS marketing (
 id TINYINT PRIMARY KEY, ads_id VARCHAR(120) NOT NULL DEFAULT '', ads_label VARCHAR(120) NOT NULL DEFAULT '',
 ga_id VARCHAR(120) NOT NULL DEFAULT '', pixel_id VARCHAR(120) NOT NULL DEFAULT '',
 seo_title VARCHAR(150) NOT NULL DEFAULT '', seo_description VARCHAR(350) NOT NULL DEFAULT '',
 canonical VARCHAR(2048) NOT NULL DEFAULT '', verification VARCHAR(120) NOT NULL DEFAULT '', reviews_url VARCHAR(2048) NOT NULL DEFAULT ''
) ENGINE=InnoDB;
